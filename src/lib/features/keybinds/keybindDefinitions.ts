import type {
  KeybindAction,
  KeybindBinding,
  KeybindCategory,
  KeybindContext,
} from "$lib/features/keybinds/keybindTypes";

function key(
  value: string,
  mods: Partial<Pick<KeybindBinding, "ctrl" | "alt" | "shift" | "meta">> = {},
): KeybindBinding {
  return {
    key: value,
    ctrl: mods.ctrl ?? false,
    alt: mods.alt ?? false,
    shift: mods.shift ?? false,
    meta: mods.meta ?? false,
  };
}

